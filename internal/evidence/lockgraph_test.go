func mustGraph(t *testing.T, dir string, rel string) *depGraph {
	t.Helper()
	read := func(p string) []byte {
		b, err := readRel(dir, p)
		if err != nil {
			return nil
		}
		return b
	}
	data := read(rel)
	if data == nil {
		t.Fatalf("missing %s", rel)
	}
	g := loadGraph(rel, data, read)
	if g == nil {
		t.Fatalf("no graph for %s", rel)
	}
	return g
}

func TestPackageLockV3(t *testing.T) {
	dir := writeTree(t, map[string]string{
		"package-lock.json": `{
  "lockfileVersion": 3,
  "packages": {
    "": {"dependencies": {"express": "^4"}, "devDependencies": {"jest": "^29"}},
    "node_modules/express": {"version": "4.18.2", "dependencies": {"qs": "6.11.0", "body-parser": "1.20.1"}},
    "node_modules/body-parser": {"version": "1.20.1", "dependencies": {"qs": "6.11.0"}},
    "node_modules/qs": {"version": "6.11.0"},
    "node_modules/jest": {"version": "29.0.0", "dev": true, "dependencies": {"minimist": "1.2.0"}},
    "node_modules/minimist": {"version": "1.2.0", "dev": true},
    "node_modules/jest/node_modules/minimist": {"version": "1.2.5", "dev": true}
  }
}`,
	})
	g := mustGraph(t, dir, "package-lock.json")
	if !g.HasEdges || !g.DevFlags || !g.RootKnown || !g.DevSplit {
		t.Fatalf("flags: %+v", g)
	}
	if got := g.dependents("qs"); !reflect.DeepEqual(got, []string{"body-parser", "express"}) {
		t.Fatalf("dependents(qs) = %v", got)
	}
	if dev, known := g.devOnly("minimist"); !dev || !known {
		t.Fatalf("minimist dev=%v known=%v", dev, known)
	}
	if dev, known := g.devOnly("qs"); dev || !known {
		t.Fatalf("qs dev=%v known=%v", dev, known)
	}
	paths := g.pathsTo("qs", 3)
	if len(paths) != 1 || !reflect.DeepEqual(paths[0], []string{"express", "qs"}) {
		t.Fatalf("paths = %v", paths)
	}
	if got := g.dependents("express"); len(got) != 0 {
		t.Fatalf("express dependents = %v", got)
	}
}

