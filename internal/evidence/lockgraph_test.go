func splitMaven(name string) (string, string, bool) {
	g, a, ok := cut(name, "/")
	return g, a, ok
}

func cut(s, sep string) (string, string, bool) {
	for i := 0; i+len(sep) <= len(s); i++ {
		if s[i:i+len(sep)] == sep {
			return s[:i], s[i+len(sep):], true
		}
	}
	return s, "", false
}

// ---- strong rules through the scan ----

func strongKinds(items []Item) []string {
	var out []string
	for _, it := range items {
		if it.Strong {
			out = append(out, string(it.Kind))
		}
	}
	sort.Strings(out)
	return out
}

func TestStrongDevDependencyFromLockfile(t *testing.T) {
	c := &Collector{}
	dir := writeTree(t, map[string]string{
		"package.json": `{"dependencies":{"express":"^4"},"devDependencies":{"jest":"^29"}}`,
		"package-lock.json": `{"lockfileVersion": 3, "packages": {
  "": {"dependencies": {"express": "^4"}, "devDependencies": {"jest": "^29"}},
  "node_modules/express": {"version": "4.18.2", "dependencies": {"qs": "6.11.0"}},
  "node_modules/qs": {"version": "6.11.0"},
  "node_modules/jest": {"version": "29.0.0", "dev": true, "dependencies": {"minimist": "1.2.0"}},
  "node_modules/minimist": {"version": "1.2.0", "dev": true}
}}`,
		"src/app.js": "const express = require('express');\n",
	})
	t.Run("transitive dev-only is strong", func(t *testing.T) {
		items := c.ecosystemEvidence(dir, source.Finding{PURL: "pkg:npm/minimist@1.2.0"})
		if got := strongKinds(items); !reflect.DeepEqual(got, []string{string(KindDevDependency)}) {
			t.Fatalf("strong = %v, all = %v", got, kindsOf(items))
		}
		if !hasKind(items, KindTransitive) || !hasKind(items, KindDependencyPath) {
			t.Fatalf("kinds = %v", kindsOf(items))
		}
	})
	t.Run("runtime transitive is not strong and carries a path", func(t *testing.T) {
		items := c.ecosystemEvidence(dir, source.Finding{PURL: "pkg:npm/qs@6.11.0"})
		if got := strongKinds(items); len(got) != 0 {
			t.Fatalf("strong = %v", got)
		}
		for _, it := range items {
			if it.Kind == KindDependencyPath {
				if ps, _ := it.Details["paths"].([]string); len(ps) != 1 || ps[0] != "express → qs" {
					t.Fatalf("paths = %v", it.Details["paths"])
				}
				return
			}
		}
		t.Fatalf("no dependency_path: %v", kindsOf(items))
	})
	t.Run("manifest dev but lockfile runtime is not dev", func(t *testing.T) {
		dir := writeTree(t, map[string]string{
			"package.json": `{"dependencies":{"a":"1"},"devDependencies":{"qs":"6"}}`,
			"package-lock.json": `{"lockfileVersion": 3, "packages": {
  "": {"dependencies": {"a": "1"}, "devDependencies": {"qs": "6"}},
  "node_modules/a": {"version": "1.0.0", "dependencies": {"qs": "6.11.0"}},
  "node_modules/qs": {"version": "6.11.0"}
}}`,
		})
		items := c.ecosystemEvidence(dir, source.Finding{PURL: "pkg:npm/qs@6.11.0"})
		if hasKind(items, KindDevDependency) {
			t.Fatalf("qs is in the runtime closure: %v", kindsOf(items))
		}
	})
}

func TestStrongImportNotFound(t *testing.T) {
	c := &Collector{}
	lock := `{"lockfileVersion": 3, "packages": {
  "": {"dependencies": {"left-pad": "1", "express": "4"}},
  "node_modules/left-pad": {"version": "1.3.0"},
  "node_modules/express": {"version": "4.18.2", "dependencies": {"qs": "6"}},
  "node_modules/qs": {"version": "6.11.0"}
}}`
	base := map[string]string{
		"package.json":      `{"dependencies":{"left-pad":"1","express":"4"},"scripts":{"start":"node src/app.js"}}`,
		"package-lock.json": lock,
		"src/app.js":        "const express = require('express');\n",
		"test/pad.test.js":  "const pad = require('left-pad');\n",
	}
	t.Run("direct, sole consumer, not imported → strong", func(t *testing.T) {
		items := c.ecosystemEvidence(writeTree(t, base), source.Finding{PURL: "pkg:npm/left-pad@1.3.0"})
		if got := strongKinds(items); !reflect.DeepEqual(got, []string{string(KindImportNotFound)}) {
			t.Fatalf("strong = %v, all = %v", got, kindsOf(items))
		}
	})
	t.Run("transitive with dependents is not strong", func(t *testing.T) {
		items := c.ecosystemEvidence(writeTree(t, base), source.Finding{PURL: "pkg:npm/qs@6.11.0"})
		if got := strongKinds(items); len(got) != 0 {
			t.Fatalf("strong = %v", got)
		}
	})
	t.Run("BOMHort says transitive → not strong", func(t *testing.T) {
		items := c.ecosystemEvidence(writeTree(t, base), source.Finding{PURL: "pkg:npm/left-pad@1.3.0", DirectKnown: true, Direct: false})
		if got := strongKinds(items); len(got) != 0 {
			t.Fatalf("strong = %v", got)
		}
	})
	t.Run("used in npm scripts → not strong", func(t *testing.T) {
		files := map[string]string{}
		for k, v := range base {
			files[k] = v
		}
		files["package.json"] = `{"dependencies":{"left-pad":"1","express":"4"},"scripts":{"pad":"left-pad 5"}}`
		items := c.ecosystemEvidence(writeTree(t, files), source.Finding{PURL: "pkg:npm/left-pad@1.3.0"})
		if got := strongKinds(items); len(got) != 0 {
			t.Fatalf("strong = %v", got)
		}
	})
	t.Run("without lockfile → not strong", func(t *testing.T) {
		files := map[string]string{}
		for k, v := range base {
			files[k] = v
		}
		delete(files, "package-lock.json")
		items := c.ecosystemEvidence(writeTree(t, files), source.Finding{PURL: "pkg:npm/left-pad@1.3.0"})
		if got := strongKinds(items); len(got) != 0 {
			t.Fatalf("strong = %v", got)
		}
	})
	t.Run("no source files at all → not strong", func(t *testing.T) {
		files := map[string]string{"package.json": base["package.json"], "package-lock.json": lock}
		items := c.ecosystemEvidence(writeTree(t, files), source.Finding{PURL: "pkg:npm/left-pad@1.3.0"})
		if got := strongKinds(items); len(got) != 0 {
			t.Fatalf("strong = %v", got)
		}
	})
	t.Run("pypi never strong (import names inferred)", func(t *testing.T) {
		dir := writeTree(t, map[string]string{
			"pyproject.toml": "[project]\nname = \"demo\"\ndependencies = [\"httpx\"]\n",
			"uv.lock":        "[[package]]\nname = \"demo\"\nversion = \"0.1.0\"\nsource = { editable = \".\" }\ndependencies = [{ name = \"httpx\" }]\n\n[[package]]\nname = \"httpx\"\nversion = \"0.27.0\"\nsource = { registry = \"x\" }\n",
			"demo/main.py":   "import sys\n",
		})
		items := c.ecosystemEvidence(dir, source.Finding{PURL: "pkg:pypi/httpx@0.27.0"})
		if got := strongKinds(items); len(got) != 0 {
			t.Fatalf("strong = %v", got)
		}
		if !hasKind(items, KindImportNotFound) || !hasKind(items, KindDependencyPath) {
			t.Fatalf("kinds = %v", kindsOf(items))
		}
	})
}

func TestComposerNamespaceImportScan(t *testing.T) {
	c := &Collector{}
	files := map[string]string{
		"composer.json": `{"require":{"monolog/monolog":"^3","league/csv":"^9"}}`,
		"composer.lock": `{"packages":[
  {"name":"monolog/monolog","require":{"psr/log":"^3"},"autoload":{"psr-4":{"Monolog\\":"src/Monolog"}}},
  {"name":"psr/log","require":{},"autoload":{"psr-4":{"Psr\\Log\\":"src"}}},
  {"name":"league/csv","require":{},"autoload":{"psr-4":{"League\\Csv\\":"src"}}}
 ],"packages-dev":[]}`,
		"app/Log.php":       "<?php\nnamespace App;\nuse Monolog\\Logger;\nclass Log { function l() { return new \\Monolog\\Handler\\StreamHandler('x'); } }\n",
		"tests/CsvTest.php": "<?php\nuse League\\Csv\\Reader;\n",
	}
	dir := writeTree(t, files)
	items := c.ecosystemEvidence(dir, source.Finding{PURL: "pkg:composer/monolog/monolog@3.0.0"})
	if !hasKind(items, KindPackageImported) {
		t.Fatalf("monolog kinds = %v", kindsOf(items))
	}
	// league/csv: direct, nobody depends on it, only a test file uses it → strong.
	items = c.ecosystemEvidence(dir, source.Finding{PURL: "pkg:composer/league/csv@9.0.0"})
	if got := strongKinds(items); !reflect.DeepEqual(got, []string{string(KindImportNotFound)}) {
		t.Fatalf("league/csv strong = %v, all = %v", got, kindsOf(items))
	}
	// psr/log: transitive with a dependent → never strong.
	items = c.ecosystemEvidence(dir, source.Finding{PURL: "pkg:composer/psr/log@3.0.0"})
	if got := strongKinds(items); len(got) != 0 {
		t.Fatalf("psr/log strong = %v", got)
	}
	// Package without namespaces in the lockfile: no import claim at all.
	items = c.ecosystemEvidence(dir, source.Finding{PURL: "pkg:composer/unknown/pkg@1.0.0"})
	if hasKind(items, KindImportNotFound) || hasKind(items, KindPackageImported) {
		t.Fatalf("unknown/pkg kinds = %v", kindsOf(items))
	}
}

